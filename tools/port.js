// Lifts Daylight's rules, items, recipes and screens out of the main game's script, word for word, so the first person
// version plays by exactly the same numbers. Run: node tools/port.js <main game script> > src/ported.js
// It follows every name the chosen roots use, stops at the names this version provides itself (drawing, the player, the enemies),
// and writes the pieces out in the order they appear in the main game.
const fs = require('fs'), acorn = require('acorn'), walk = require('acorn-walk');
const src = fs.readFileSync(process.argv[2], 'utf8');
const cfg = require('./port.config.js');
const ast = acorn.parse(src, { ecmaVersion: 2022, sourceType: 'script', locations: true });
const items = [];
for (const st of ast.body) {
  const it = { names: [], start: st.start, end: st.end, line: st.loc.start.line, refs: new Set() };
  if (st.type === 'FunctionDeclaration' || st.type === 'ClassDeclaration') it.names.push(st.id.name);
  else if (st.type === 'VariableDeclaration') for (const d of st.declarations) walk.full(d.id, n => { if (n.type === 'Identifier') it.names.push(n.name); });
  walk.full(st, n => { if (n.type === 'Identifier') it.refs.add(n.name); });
  items.push(it);
}
const byName = new Map(); items.forEach((it, i) => it.names.forEach(n => byName.set(n, i)));
const stop = new Set(cfg.stop), inc = new Set(), q = [...cfg.roots];
const add = i => { if (inc.has(i)) return; inc.add(i); for (const r of items[i].refs) if (!stop.has(r) && byName.has(r)) q.push(r); };
for (const L of cfg.lines) { const i = items.findIndex(it => it.line === L); if (i < 0) throw new Error('no statement at line ' + L); add(i); }
while (q.length) { const n = q.shift(); if (stop.has(n)) continue; const i = byName.get(n); if (i === undefined) continue; add(i); }
const used = new Set();
let out = '// ---- generated by tools/port.js from the main game: do not edit by hand, change tools/port.config.js ----\n';
for (const i of [...inc].sort((a, b) => a - b)) {
  let s = src.slice(items[i].start, items[i].end);
  for (const [name, pairs] of Object.entries(cfg.patch)) if (items[i].names.includes(name) || name === '@' + items[i].line) {
    for (const [a, b] of pairs) { if (!s.includes(a)) throw new Error(`patch for ${name} not found: ${a}`); s = s.split(a).join(b); }
    used.add(name);
  }
  out += s + '\n';
}
for (const k of Object.keys(cfg.patch)) if (!used.has(k)) throw new Error('unused patch ' + k);
for (const [a, b] of cfg.everywhere || []) { if (!out.includes(a)) throw new Error('not found anywhere: ' + a); out = out.split(a).join(b); }
process.stdout.write(out);
const need = new Set(); for (const i of inc) for (const r of items[i].refs) if (stop.has(r)) need.add(r);
console.error(`${inc.size} pieces, ${out.length} chars · provided here: ${[...need].sort().join(' ')}`);
